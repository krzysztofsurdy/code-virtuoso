#!/usr/bin/env bash
set -euo pipefail
cat > package.json <<'JSON'
{
  "name": "shop",
  "scripts": {"test": "vitest run", "lint": "eslint .", "gen": "node scripts/gen.js"},
  "devDependencies": {"vitest": "^2.0.0", "eslint": "^9.0.0"}
}
JSON
printf 'lockfileVersion: 9.0\n' > pnpm-lock.yaml
mkdir -p generated .github/workflows
echo "// generated by pnpm gen" > generated/api.ts
cat > .github/workflows/ci.yml <<'YML'
name: ci
on: [push]
jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - run: pnpm install --frozen-lockfile
      - run: pnpm lint
      - run: pnpm test
YML
